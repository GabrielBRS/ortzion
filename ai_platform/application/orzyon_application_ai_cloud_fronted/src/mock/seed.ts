function dep(
  id: string,
  clusterId: string,
  modelId: string,
  engineId: string,
  quantization: Quantization,
  contextLength: number,
  status: ModelDeployment['status'] = 'disponivel',
  failureReason?: string,
  device: ModelDeployment['device'] = 'gpu',
): ModelDeployment {
  const cluster = clusters.find((c) => c.id === clusterId)!
  const model = models.find((m) => m.id === modelId)!
    const est = estimateModelMemory(model, quantization, contextLength)
  return {
    id,
    clusterId,
    name: `${slugify(model.name)}-${quantization.toLowerCase()}`,
    modelId,
    engineId,
    device,
    quantization,
    contextLength,
    status,
    failureReason,
    reservation: deploymentReservation(cluster, device, est),
    createdAt: ago(20 * DAY),
  }
}

